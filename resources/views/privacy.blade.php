        <p>Welcome to <strong>Life in Rolls</strong> (“we”, “our”, or “us”). We are dedicated to delivering an authentic retro analog photography experience while respecting and protecting your privacy. This Privacy Policy explains our practices regarding data collection, photo processing, storage, sharing, and your rights.</p>

        <h2>1. Personal & Account Information</h2>
        <p>When you register and use Life in Rolls, we collect basic identification data:</p>
        <ul>
            <li><strong>Account Credentials:</strong> Your full name, registered email address, and encrypted hashed password.</li>
            <li><strong>Profile Preferences:</strong> Camera preset selections, aspect ratio preferences, and exposure defaults.</li>
        </ul>

        <h2>2. Uploaded Photos & Media Processing</h2>
        <p>When you capture or upload photos using our simulated analog camera filters:</p>
        <ul>
            <li><strong>Photo Assets:</strong> Uploaded images and film scans are processed using 3D color lookup tables (LUTs), vintage grain, vignette, and optional date stamp overlays.</li>
            <li><strong>Photo Metadata:</strong> Camera profile used (e.g. Classic 35, FNC CAM 800, CCD Pop), aspect ratio (4:3, 1:1, 16:9, 3:2), capture timestamp, and exposure settings.</li>
            <li><strong>Device Permissions:</strong> We request access to your <em>Camera</em> (to capture live frames) and <em>Photo Storage</em> (to save developed negatives or import pictures). Photos are only accessed when explicitly initiated by you.</li>
        </ul>

        <h2>3. Film-Roll Membership & Invitations</h2>
        <p>Life in Rolls provides collaborative shared rolls:</p>
        <ul>
            <li><strong>Roll Collaboration:</strong> When you create or join a shared film roll, your name and contributed photos are visible to the other invited members of that specific roll.</li>
            <li><strong>Invite Tokens & Codes:</strong> We generate unique cryptographic tokens and 6-character invite codes to allow you to securely invite friends and family to your rolls.</li>
            <li><strong>Moderation:</strong> Roll creators can manage member permissions and remove contributors if necessary.</li>
        </ul>

